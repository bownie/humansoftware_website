/**
 * Writes `_redirects` and `_headers` into the build output so Cloudflare Pages
 * answers the retired URLs with real 301s instead of the meta-refresh pages
 * Astro emits for static hosts that cannot set a status code. The redirects come
 * from the same `redirects` config, so the two cannot drift.
 */
const cloudflarePages = (): AstroIntegration => {
  let exact: Record<string, string> = {};

  return {
    name: "cloudflare-pages-output",
    hooks: {
      "astro:config:done": ({ config: astroConfig }) => {
        exact = Object.fromEntries(
          Object.entries(astroConfig.redirects).map(([from, to]) => [
            from,
            typeof to === "string" ? to : to.destination,
          ])
        );
      },
      "astro:build:done": async ({ dir, logger }) => {
        const rules = new Set<string>();

        for (const [from, to] of Object.entries(exact)) {
          const path = withBase(from);
          // Cloudflare matches the requested path exactly, so cover both the
          // slash and no-slash shapes of every redirect.
          const twin = path.endsWith("/") ? path.slice(0, -1) : `${path}/`;
          for (const variant of [path, twin]) {
            if (variant) rules.add(`${variant} ${to} 301`);
          }
        }

        for (const [from, to] of Object.entries(splatRedirects)) {
          rules.add(`${withBase(from)} ${withBase(to)} 301`);
        }

        const lines = [
          "# Generated by the cloudflare-pages-output integration in astro.config.ts.",
          "# Cloudflare Pages parses this file; it is never served to visitors.",
          "# Exact rules first, then splats.",
          "",
          ...rules,
        ];

        await writeFile(
          new URL("_redirects", dir),
          `${lines.join("\n")}\n`,
          "utf8"
        );
        await writeFile(new URL("_headers", dir), cloudflareHeaders, "utf8");
        logger.info(
          `_redirects written with ${rules.size} rules, plus _headers`
        );
      },
    },
  };
};

